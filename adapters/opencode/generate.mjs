// Pure generator: protocol roles + models.json -> OpenCode files. No I/O besides reading inputs.
import { readFileSync, readdirSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const templates = join(dirname(fileURLToPath(import.meta.url)), "templates")

export function parseRole(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!m) throw new Error("role is missing frontmatter")
  const meta = {}
  let nested = null
  for (const line of m[1].split("\n")) {
    const sub = line.match(/^  (\w+):\s*(.+)$/)
    if (sub && nested) { meta[nested][sub[1]] = sub[2].trim(); continue }
    const kv = line.match(/^(\w+):\s*(.*)$/)
    if (!kv) continue
    if (kv[2] === "") { nested = kv[1]; meta[nested] = {} } else { nested = null; meta[kv[1]] = kv[2].trim() }
  }
  return { meta, body: m[2].trim() }
}

export function loadRoles(dir) {
  return readdirSync(dir).filter((f) => f.endsWith(".md")).sort()
    .map((f) => parseRole(readFileSync(join(dir, f), "utf8")))
}

export function resolveModel(models, alias) {
  const id = models.aliases[alias]
  if (!id) throw new Error(`unknown model alias "${alias}" (known: ${Object.keys(models.aliases).join(", ")})`)
  return id
}

export function generate({ models, roles }) {
  const primary = roles.find((r) => r.meta.mode === "primary")
  const config = {
    $schema: "https://opencode.ai/config.json",
    ...(primary && { default_agent: primary.meta.name }),
    model: resolveModel(models, "strong"),
    small_model: resolveModel(models, "fast"),
    ...(models.proxy && { provider: { [models.proxy.provider]: { options: { baseURL: models.proxy.baseURL } } } }),
  }
  const files = { "opencode.json": JSON.stringify(config, null, 2) + "\n" }
  for (const { meta, body } of roles) {
    const perm = Object.entries(meta.permission ?? {}).map(([k, v]) => `  ${k}: ${v}`).join("\n")
    files[`.opencode/agents/${meta.name}.md`] =
      `---\ndescription: ${meta.description}\nmode: ${meta.mode}\nmodel: ${resolveModel(models, meta.model)}\n` +
      (perm ? `permission:\n${perm}\n` : "") +
      `---\n<!-- generated by commitar-oc from protocol/roles/${meta.name}.md; do not edit -->\n${body}\n`
  }
  files[".opencode/lib/gates-core.mjs"] = readFileSync(join(templates, "gates-core.mjs"), "utf8")
  files[".opencode/tools/gates.ts"] = readFileSync(join(templates, "gates.ts"), "utf8")
  return files
}
