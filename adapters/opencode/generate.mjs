// Pure generator: protocol roles + models.json -> OpenCode files. No I/O besides reading inputs.
import { readFileSync, readdirSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const templates = join(dirname(fileURLToPath(import.meta.url)), "templates")

const unquote = (v) => (v.startsWith('"') ? JSON.parse(v) : v)

export function parseRole(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!m) throw new Error("role is missing frontmatter")
  const meta = {}
  let nested = null
  for (const line of m[1].split("\n")) {
    const sub = line.match(/^  (\w+):\s*(.+)$/)
    if (sub && nested) { meta[nested][sub[1]] = sub[2].trim(); continue }
    const kv = line.match(/^(\w+):\s*(.*)$/)
    if (!kv) continue
    if (kv[2] === "") { nested = kv[1]; meta[nested] = {} } else { nested = null; meta[kv[1]] = unquote(kv[2].trim()) }
  }
  return { meta, body: m[2].trim() }
}

export function loadRoles(dir) {
  return readdirSync(dir).filter((f) => f.endsWith(".md")).sort()
    .map((f) => parseRole(readFileSync(join(dir, f), "utf8")))
}

export function resolveModel(models, alias) {
  const id = models.aliases[alias]
  if (!id) throw new Error(`unknown model alias "${alias}" (known: ${Object.keys(models.aliases).join(", ")})`)
  return id
}

// Narrow bash allowlist for roles whose bash is `ask`: the project's own gate commands and read-only git
// are allowed; staging/committing only for roles that may edit. Last matching rule wins, so the denies come last.
export function bashRules(gates, canEdit) {
  const rules = [["*", "ask"]]
  for (const cmd of Object.values(gates ?? {}).filter((c) => typeof c === "string" && c.trim())) {
    rules.push([cmd.trim(), "allow"], [`${cmd.trim()} *`, "allow"])
  }
  for (const g of ["git status", "git diff", "git log", "git show"]) rules.push([g, "allow"], [`${g} *`, "allow"])
  if (canEdit) for (const g of ["git add", "git commit"]) rules.push([g, "allow"], [`${g} *`, "allow"])
  for (const d of ["rm -rf *", "git push *", "git reset --hard *"]) rules.push([d, "deny"])
  return rules
}

export function generate({ models, roles, vault = null, gates = { test: "npm test" } }) {
  const primary = roles.find((r) => r.meta.mode === "primary")
  const config = {
    $schema: "https://opencode.ai/config.json",
    ...(primary && { default_agent: primary.meta.name }),
    model: resolveModel(models, "strong"),
    small_model: resolveModel(models, "fast"),
    ...(models.proxy && { provider: { [models.proxy.provider]: { options: { baseURL: models.proxy.baseURL } } } }),
  }
  const files = { "opencode.json": JSON.stringify(config, null, 2) + "\n" }
  const specialists = roles.filter((r) => r.meta.mode === "subagent")
  const roster = `\n\n## Available subagents\n${specialists.map((r) => `- @${r.meta.name}: ${r.meta.description}`).join("\n")}`
  const vaultNote = `\n\n## Knowledge vault\nAfter the SPEC gate passes, call the \`vault_save\` tool with kind "spec" and a short summary of the spec (goal, acceptance criteria, key decisions). The spec itself stays in the project and the handoff never depends on the vault: if \`vault_save\` reports an error, mention it and continue.`
  // OpenCode v2 exposes custom tools only through `execute`; free models do not infer that.
  const callNote = (text) => {
    const used = ["gates", "vault_save"].filter((n) => text.includes(`\`${n}\``))
    if (!used.length) return ""
    return `\n\n## Calling the tools\n${used.map((n) => `\`${n}\``).join(" and ")} ${used.length > 1 ? "are" : "is"} called through the \`execute\` tool as \`tools.<name>(args)\`, e.g. \`return await tools.${used[0]}(...)\`. Do not run them with bash; if \`execute\` is missing, say so instead of running the commands yourself.`
  }
  for (const { meta, body: rawBody } of roles) {
    const full = meta.mode === "primary" ? rawBody + roster + (vault ? vaultNote : "") : rawBody
    const body = full + callNote(full)
    const perm = Object.entries(meta.permission ?? {}).map(([k, v]) => {
      if (k !== "bash" || v !== "ask") return `  ${k}: ${v}`
      const rules = bashRules(gates, (meta.permission.edit ?? "ask") !== "deny")
      return `  bash:\n${rules.map(([pat, eff]) => `    ${JSON.stringify(pat)}: ${eff}`).join("\n")}`
    }).join("\n")
    files[`.opencode/agents/${meta.name}.md`] =
      `---\ndescription: ${JSON.stringify(meta.description)}\nmode: ${meta.mode}\nmodel: ${resolveModel(models, meta.model)}\n` +
      (perm ? `permission:\n${perm}\n` : "") +
      `---\n<!-- generated by commitar-oc from protocol/roles/${meta.name}.md; do not edit -->\n${body}\n`
  }
  files[".opencode/lib/gates-core.mjs"] = readFileSync(join(templates, "gates-core.mjs"), "utf8")
  files[".opencode/tools/gates.ts"] = readFileSync(join(templates, "gates.ts"), "utf8")
  if (vault) {
    files[".opencode/lib/vault-core.mjs"] = readFileSync(join(templates, "vault-core.mjs"), "utf8")
    files[".opencode/tools/vault_save.ts"] = readFileSync(join(templates, "vault.ts"), "utf8").replace("__VAULT_PATH__", JSON.stringify(vault.path))
  }
  let plugin = readFileSync(join(templates, "plugin-v2.ts"), "utf8").replace("__VAULT_PATH__", vault ? JSON.stringify(vault.path) : "null")
  if (!vault) plugin = plugin.replace(/^import \{ saveNote \}.*\n/m, "")
  files[".opencode/plugins/commitar/index.ts"] = plugin
  return files
}
